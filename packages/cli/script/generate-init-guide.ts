#!/usr/bin/env tsx
/**
 * Embed the Agent Setup Guide
 *
 * `init.md` is the guide a coding agent follows to add Sentry to a project.
 * `sentry init` prints it, and the docs site serves the same file at
 * https://cli.sentry.dev/init.md (`apps/cli-docs/public/init.md` is a symlink
 * to it). The single-file binary can't read the file from disk at runtime, so
 * this script writes it into a module.
 *
 * Usage:   tsx script/generate-init-guide.ts
 * Output:  src/generated/init-guide.ts
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_PATH = join(PACKAGE_ROOT, "init.md");
const OUT_PATH = join(PACKAGE_ROOT, "src", "generated", "init-guide.ts");

const guide = readFileSync(SOURCE_PATH, "utf-8");

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(
  OUT_PATH,
  [
    "// Generated by script/generate-init-guide.ts from init.md. Do not edit.",
    "",
    "/** The agent setup guide that `sentry init` prints. */",
    `export const INIT_GUIDE = ${JSON.stringify(guide)};`,
    "",
  ].join("\n"),
);
